""" Si scriva un programma che legge tre numeri interi e visualizza la media dei tre numeri."""

x: int = int(input("Inserisci il primo numero: "))
y: int = int(input("Inserisci il secondo numero: "))
z: int = int(input("Inserisci il terzo numero: "))


media= (x+y+z)/3
print(f"La media dei tre numeri e': {media}")
