''' programma che calcola l'area del cerchio'''
# asseggnazione variabile del raggio
raggio = int(input("inserisci un valore per il raggio:\n"))     

# visualizza il valore del raggio
print("il valore del raggio e':\n", raggio)

#calcolo dell'area del cerchio
PI=3.14
area= raggio*raggio*PI

#visualizza il valore dell'area
print ("il valore dell'area del cerchio e':\n", area)